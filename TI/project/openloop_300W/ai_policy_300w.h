static float ai300_sig(float x)
{
    if (x > 20.0f)  { x = 20.0f; }
    if (x < -20.0f) { x = -20.0f; }
    return 1.0f / (1.0f + expf(-x));
}

/* DBN前向推理: 输入物理量 -> 输出物理量(已限幅到训练域/物理可行域) */
static void ai300_recipe(float vin, float vref, float io,
                         float *fs_khz, float *d1_tbl, float *d2, float *phi_ns)
{
    float x[4];
    float a1[AI300_H1], a2[AI300_H2], z3[4];
    int i, j;

    /* 训练域: Vin/Vref 24~48V, Io 0~15A */
    if (vin  < 24.0f) { vin  = 24.0f; }
    if (vin  > 48.0f) { vin  = 48.0f; }
    if (vref < 24.0f) { vref = 24.0f; }
    if (vref > 48.0f) { vref = 48.0f; }
    if (io   < 0.0f)  { io   = 0.0f; }
    if (io   > 15.0f) { io   = 15.0f; }

    x[0] = (vin - AI300_MX[0]) / AI300_SX[0];
    x[1] = (vref - AI300_MX[1]) / AI300_SX[1];
    x[2] = (io - AI300_MX[2]) / AI300_SX[2];
    x[3] = (vref / vin - AI300_MX[3]) / AI300_SX[3];

    for (j = 0; j < AI300_H1; j++) {
        float s = AI300_B1[j];
        for (i = 0; i < 4; i++) { s += x[i] * AI300_W1[i * AI300_H1 + j]; }
        a1[j] = ai300_sig(s);
    }
    for (j = 0; j < AI300_H2; j++) {
        float s = AI300_B2[j];
        for (i = 0; i < AI300_H1; i++) { s += a1[i] * AI300_W2[i * AI300_H2 + j]; }
        a2[j] = ai300_sig(s);
    }
    for (j = 0; j < 4; j++) {
        float s = AI300_B3[j];
        for (i = 0; i < AI300_H2; i++) { s += a2[i] * AI300_W3[i * 4 + j]; }
        z3[j] = s;
    }

    *fs_khz  = z3[0] * AI300_SY[0] + AI300_MY[0];
    *d1_tbl  = z3[1] * AI300_SY[1] + AI300_MY[1];
    *d2      = z3[2] * AI300_SY[2] + AI300_MY[2];
    *phi_ns  = z3[3] * AI300_SY[3] + AI300_MY[3];

    /* 物理限幅 */
    if (*fs_khz < 30.0f)   { *fs_khz = 30.0f; }
    if (*fs_khz > 300.0f)  { *fs_khz = 300.0f; }
    if (*d1_tbl < 0.20f)   { *d1_tbl = 0.20f; }
    if (*d1_tbl > 0.95f)   { *d1_tbl = 0.95f; }
    if (*d2 < 0.30f)       { *d2 = 0.30f; }
    if (*d2 > 0.80f)       { *d2 = 0.80f; }
    if (*phi_ns < 0.0f)    { *phi_ns = 0.0f; }
    if (*phi_ns > 3500.0f) { *phi_ns = 3500.0f; }
}
